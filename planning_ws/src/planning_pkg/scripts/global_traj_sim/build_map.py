#   (B) 라인 위의 '속도'를 정하는 값 — V_MAX, MU_PROFILE, LAT_ERR_*, A_*_CORNER
#       CSV 의 vx/ax 열만 바꾼다. 주행선은 한 점도 안 움직인다.
#   (C) 검증/보고용 값             — MU, MARGIN, CAR_*, JERK_REPORT_LIMIT
#       프로파일을 만들지 않고, 만들어진 것을 검사하거나 CSV 보고값만 줄인다.
#
# "레이스라인은 그대로 두고 속도만 올리고 싶다" = (B) 만 만지면 된다. 실제로
# --lat-err-corner 만 바꿔 재생성하면 s/x/y/d_left/d_right/psi/kappa 열이
# maxdiff 0.0 으로 비트 단위 동일하고 vx/ax 만 바뀐다 (2026-08-09 확인).
#
# ── (B) 속도가 정해지는 순서 ────────────────────────────────────────────────
#
#   1) 점마다 '정적 상한' 3개를 계산해서 그중 **최소값**을 쓴다.
#
#        곡률 상한 = sqrt(MU_PROFILE * g / |kappa|)
#            "이 반경을 이 속도로 돌면 타이어가 미끄러진다"는 물리 한계.
#            반경이 작을수록(코너가 급할수록) 낮아진다.
#
#        폭 상한   = (벽까지 여유 - 차 반폭) / lat_err_slope
#            "라인을 정확히 못 따라가고 옆으로 밀리는 만큼은 벽 여유에서
#             까먹는다"는 기하 한계. 자세한 건 아래 lat_err_slope 설명.
#
#        V_MAX     = 그냥 상수 천장.
#
#   2) velocity_profile() 이 그 상한들 사이를 가감속 램프로 잇는다.
#      한 점이 3.0 m/s 로 묶이면 그 앞은 감속으로, 뒤는 가속으로 이어야 하므로
#      **상한에 실제로 붙어 있는 점보다 램프 위에 있는 점이 훨씬 많다**
#      (my_track0808 기준 92.6% 가 램프 위). 그래서 어느 한 점의 상한을
#      낮추면 그 주변 수 미터가 통째로 느려진다.
#      램프의 기울기는 A_ACC_MAX / A_DEC_PLANNED (직선) 와
#      A_ACC_CORNER / A_DEC_CORNER (코너) 가 정한다.
#
#   3) smooth_longitudinal() 이 톱니를 깎는다. **낮추기만** 한다.
#
# ── lat_err_slope 가 뭔가 (--lat-err-straight / --lat-err-corner) ───────────
#
#   단위는 [초]다. 뜻은 "속도 1 m/s 당 몇 m 나 라인 밖으로 밀려나는가".
#
#       예상 횡추적오차 [m] = lat_err_slope [s] * 속도 [m/s]
#
#   실차는 계획된 라인을 정확히 밟지 못하고 코너 바깥으로 조금씩 밀린다
#   (pure pursuit 의 lookahead 가 라인 바깥을 당긴다). 빠를수록 많이 밀린다.
#   밀려난 만큼은 벽 여유를 까먹으므로, 남은 여유를 이 기울기로 나누면
#   "그 지점에서 벽에 안 닿고 낼 수 있는 최대 속도"가 나온다:
#
#       폭 상한 = (벽까지 여유 - 차 반폭) / lat_err_slope
#
#   벽 여유 0.42 m, 차 반폭 0.15 → 쓸 수 있는 여유 0.27 m.
#     slope 0.117 이면 0.27/0.117 = 2.3 m/s 까지만 허용
#     slope 0.095 이면 0.27/0.095 = 2.9 m/s 까지 허용
#   즉 **이 값이 곧 "얼마나 못 믿는가"이고, 낮출수록 빨라진다.**
#   반대로 이 값을 실제보다 낮게 잡으면 계획이 벽 여유를 실제보다 많이
#   남을 거라 착각해서 코너에서 벽에 붙는다. 안전 마진 그 자체다.
#
#   기울기는 하나가 아니라 두 개(직선/코너)이고, 그 지점의 **직전 곡률**로
#   보간한다 (LAT_ERR_KAPPA_LOW ~ HIGH). 오차가 가장 큰 곳은 코너 안이 아니라
#   코너를 막 빠져나온 직후라서 현재 곡률이 아니라 지나온 곡률을 쓴다.
#     LAT_ERR_STRAIGHT_S      직선에서의 기울기 (작다 = 잘 따라간다)
#     LAT_ERR_CORNER_S        코너에서의 기울기 (크다 = 많이 밀린다)
#     LAT_ERR_KAPPA_LOW/HIGH  직선/코너 판정 곡률 경계
#     LAT_ERR_KAPPA_WINDOW_M  '직전 곡률'을 얼마나 뒤까지 볼지
#     LAT_ERR_EXIT_LAG_M      코너 탈출 뒤 몇 m 까지 코너와 똑같이 볼지
#     LAT_ERR_EXIT_DECAY_M    그 뒤 얼마나 빨리 직선 취급으로 돌아올지
#
#   ⚠️ 이 값은 상상해서 정하는 게 아니라 **실차 백에서 재는 값**이다.
#      /pf/pose/odom 을 CSV 에 투영해 |lat err| 를 구하고 속도로 나눈다.
#      절차는 아래 LAT_ERR_CORNER_S 주석의 실측표 참조.
#
#   ⚠️ |lat err| 를 그대로 쓰면 안 된다 — 넓은 쪽으로 밀린 오차는 벽 여유를
#      안 까먹는데도 기울기를 부풀린다. 폭 상한이 뜻하는 것은 "가용 여유를
#      1 m/s 당 몇 m 까먹는가" 이므로, 부호를 살려
#          eff = max(0, (min(d_left,d_right) - 차반폭) - 실제 차체-벽 여유)
