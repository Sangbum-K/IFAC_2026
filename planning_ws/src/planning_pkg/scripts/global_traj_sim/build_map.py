# 코너를 빠져나온 뒤 **감쇠를 시작하지도 않는** 거리 [m]. 이 거리 안에서는
# 지나온 곡률을 감쇠 없이(가중 1.0) 그대로 물고, 그 뒤부터 EXIT_DECAY_M 으로
