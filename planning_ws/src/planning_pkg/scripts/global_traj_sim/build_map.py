# 로 고정된다. 실제 CSV 의 s26.0/26.5/27.0 이 2.71/2.88/2.76 으로 직선
# 시작부 3 m 를 2.8 m/s 에 묶고 있었다 — 실차에서 느낀 "풀악셀이 늦다"의 정체다.
