#
# 아래 상수는 성격이 세 종류로 나뉜다. 섞어서 보면 안 된다.
#
#   (A) 라인의 '모양'을 정하는 값   — SAFE_DIST*, RACELINE, SP_CURV_W, INFIELD_*
