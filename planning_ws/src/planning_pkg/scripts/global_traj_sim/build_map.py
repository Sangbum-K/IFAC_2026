# hard rolling-max 는 곡률이 이미 0.03 인 s27.2 에서도 헤어핀의 0.27 을 물고
# 있어서 상한을 3 m/s 에 묶는다 — 실차에서 느낀 "풀악셀이 늦다"가 이것이다.
#
# 랩타임 영향 (라인 고정, corner_s 0.090, 2026-08-09):
#     decay 0.4 / 0.8 / 1.5  -> 랩 7.59 s, v_max 6.77  (전부 동일)
