def report_longitudinal(traj, corner_kappa=None):
    """코너/직선을 나눠 속도·가감속·저크를 보고한다.

    "코너에서 울컥거린다" / "직선에서 늦게 밟는다" 는 랩타임 한 숫자로는 절대
    안 보인다. 두 구간을 갈라서 v 와 ax 부호 반전 횟수를 따로 내야 보인다.
    """
    corner_kappa = LAT_ERR_KAPPA_HIGH if corner_kappa is None else corner_kappa
    info = traj.get("longitudinal_info") or {}
    if not info:
        return []
    v = np.asarray(traj["vx"], dtype=float)
    ax = np.asarray(traj["ax"], dtype=float)
    k = np.abs(np.asarray(traj["kappa"], dtype=float))
    s = np.asarray(traj["s"], dtype=float)
    ds = np.diff(s, append=s[-1] + (s[-1] - s[-2] if len(s) > 1 else 0.1))
    lap = float(np.sum(ds / np.maximum(v, 1e-6)))
    lines = [
        f"      [종방향] 랩 {lap:.2f} s · v {v.min():.2f}~{v.max():.2f} "
        f"(평균 {v.mean():.2f}) · ax {ax.min():+.2f}~{ax.max():+.2f} m/s²",
        f"        가감속 상한: 직선 {A_ACC_MAX:.2f}/{A_DEC_PLANNED:.2f} → "
        f"코너 {info.get('accel_limit_min', float('nan')):.2f}/"
        f"{info.get('decel_limit_min', float('nan')):.2f} m/s²",
        f"        스무딩 {info.get('smooth_passes', 0)} 패스 "
        f"(창 {LONGITUDINAL_SMOOTH_M:.2f} m): ax 부호반전 "
        f"{info.get('ax_sign_flips_before_smoothing', 0)} → "
        f"{info.get('ax_sign_flips', 0)} 회 · 저크 p99 "
        f"{info.get('jerk_p99_before_smoothing', float('nan')):.1f} → "
        f"{info.get('jerk_p99', float('nan')):.1f} m/s³ "
        f"(max {info.get('jerk_max', float('nan')):.1f}, 한계 "
        f"{info.get('jerk_limit', float('nan')):.0f} 초과 "
        f"{info.get('jerk_over_pts', 0)}점)",
    ]
    corner = k >= corner_kappa
    straight = k <= LAT_ERR_KAPPA_LOW
    for label, mask in (("코너", corner), ("직선", straight)):
        if not mask.any():
            continue
        sub_v, sub_ax = v[mask], ax[mask]
        lines.append(
            f"        {label} {int(mask.sum())}점: v {sub_v.min():.2f}~"
            f"{sub_v.max():.2f} (평균 {sub_v.mean():.2f}) · "
            f"|ax| 평균 {np.abs(sub_ax).mean():.2f} max "
            f"{np.abs(sub_ax).max():.2f} m/s²")
    return lines


def report_speed_pairing(traj, profiles):
    """프로파일 속도가 control cap 에 얼마나 잘리는지 보고한다.

    real_car.yaml 의 계약은 scale = (control cap) / V_MAX 다. 이게 어긋나면
    control 이 전 구간을 cap 상수로 뭉개서 (a) 속도 프로파일이 사라지고
    (b) 조향 LUT를 wpnt 속도로 조회하는 구조 때문에 필요 조향이 과대해진다.
    검증은 실제 cap 으로 돌기 때문에 PASS 는 나지만, 그때 달리는 라인은
    build_map 이 만든 속도 프로파일이 아니다 — 그 사실을 눈에 보이게 남긴다.
    """
    lines = []
    vx = np.asarray(traj["vx"], dtype=float)
    for profile in profiles:
        scaled = vx * profile["planner_speed_scale"] * \
            profile["controller_speed_scale"]
        cap = profile["max_speed_mps"]
        clamped = int(np.sum(scaled > cap + 1e-9))
        lines.append(
            f"      [{profile['name']}] 프로파일 속도 max "
            f"{scaled.max():.2f} m/s vs control cap {cap:.2f} → "
            f"{clamped}/{len(vx)} pt 클램프 "
            f"({100.0 * clamped / max(len(vx), 1):.1f}%)")
        if clamped > 0.2 * len(vx):
            lines.append(
                f"        [warn] 프로파일의 {100.0 * clamped / len(vx):.0f}% 가 "
                f"cap 상수로 뭉개진다. 계약대로 맞추려면 planner "
                f"velocity_scale 을 {cap / V_MAX:.4f} 로 내리거나 "
                f"control vehicle/max_speed_mps 를 "
                f"{V_MAX * profile['planner_speed_scale'] * profile['controller_speed_scale']:.2f} "
                f"로 올릴 것 (어느 쪽이 맞는지는 실차 단계 승격 판단).")
    return lines


def simulate_controller_profiles(name, traj, grid, requested_laps, profiles,
                                 advisory_profiles=()):
    """gate 프로파일은 하나라도 실패하면 전체 실패. advisory 는 보고만 한다.

    advisory 도 반드시 실행된다 — 실차 CSV를 만들 때 시뮬 프로파일 결과를 조용히
    숨기면 "시뮬에서 못 돈다"는 사실이 아무 데도 안 남는다. 승격만 막지 않는다.
    """
    all_ok = True
    messages = []
    primary_log = None
    first_failed_log = None
    for profile in profiles:
        log = PurePursuitSim(traj, profile["name"]).run(
            n_laps=requested_laps)
        ok, profile_messages = verify_simulation(
            name, log, grid, requested_laps, profile["name"])
        if primary_log is None:
            primary_log = log
        if not ok and first_failed_log is None:
            first_failed_log = log
        all_ok = all_ok and ok
        messages.extend(profile_messages)
    for profile in advisory_profiles:
        try:
            log = PurePursuitSim(traj, profile["name"]).run(
                n_laps=requested_laps)
            _, profile_messages = verify_simulation(
                name, log, grid, requested_laps, profile["name"])
        except Exception as exc:
            profile_messages = [
                f"      {name}/{profile['name']}: [FAIL] advisory 실행 예외 "
                f"{type(exc).__name__}: {exc}"]
        messages.extend(
            line.replace("[FAIL]", "[advisory FAIL]")
            for line in profile_messages)
    return all_ok, messages, primary_log, first_failed_log


